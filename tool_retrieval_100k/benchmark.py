"""Benchmark tasks: (natural-language query, gold tool id) pairs.

This module ships a small hand-curated seed set so the harness runs
out-of-the-box on a registry that contains those tools. A larger benchmark
is generated by ``scripts/generate_benchmark.py`` using Claude to draft
candidate queries which are then human-reviewed.

A task is *valid* against a given registry only if the gold tool exists.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from .registry import Registry


@dataclass(frozen=True)
class Task:
    query: str
    gold_tool_id: int
    source: str = "seed"

    def as_dict(self) -> dict:
        return {"query": self.query, "gold_tool_id": self.gold_tool_id, "source": self.source}


SEED_TASKS: list[Task] = [
    Task("Convert this paragraph of text into spoken audio.", 12),
    Task("Generate a short descriptive caption for an uploaded photograph.", 117),
    Task("Build a retrieval-augmented generation pipeline over my docs.", 1),
    Task("Stand up a vector search index for semantic lookup.", 4),
    Task("Run an evaluation suite over a fine-tuned model.", 5),
    Task("Detect when a model output is likely hallucinated.", 10010),
    Task("Probe a model's internal activations during a forward pass.", 10018),
    Task("Train a sparse autoencoder on hidden states for interpretability.", 10019),
    Task("Decide whether a user prompt is a jailbreak attempt.", 10013),
    Task("Score model outputs for toxicity before returning them.", 10006),
    Task("Detect demographic bias in classifier outputs.", 10007),
    Task("Assist a non-verbal autistic user with day-to-day communication.", 10152),
    Task("Synthesize speech that carries an emotional tone.", 10148),
    Task("Estimate the carbon footprint of a training run.", 1002),
    Task("Track research alumni across institutions.", 1001),
]


def load_tasks(path: str | Path | None = None) -> list[Task]:
    """Load tasks from JSONL, or return the seed set."""
    if path is None:
        return list(SEED_TASKS)
    tasks: list[Task] = []
    with Path(path).open("r", encoding="utf-8") as f:
        for line in f:
            obj = json.loads(line)
            tasks.append(
                Task(
                    query=obj["query"],
                    gold_tool_id=int(obj["gold_tool_id"]),
                    source=obj.get("source", "file"),
                )
            )
    return tasks


def filter_to_registry(tasks: list[Task], registry: Registry) -> list[Task]:
    """Drop tasks whose gold tool isn't present in this registry."""
    return [t for t in tasks if t.gold_tool_id in {x.tool_id for x in registry}]
